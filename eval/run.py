"""Run the evaluation scenarios against the real model.

    python eval/run.py                 # all scenarios, writes eval/results.md
    python eval/run.py --only price    # scenarios whose id contains "price"
    python eval/run.py --examples      # also write the delivered conversations to examples/

Needs GEMINI_API_KEY (see .env.example). Every scenario starts a fresh session.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT))

from dotenv import load_dotenv  # noqa: E402

load_dotenv(ROOT / ".env")

from eval.scenarios import SCENARIOS, STORE_TODAY, Result, Scenario  # noqa: E402

os.environ["EMPORIO_TODAY"] = STORE_TODAY

from emporio.agent import Agent  # noqa: E402


def run_scenario(scenario: Scenario):
    """Returns (Result, per-turn [(reply, tool calls)], model that answered)."""
    calls: list[tuple[str, dict, dict]] = []
    agent = Agent(sessions_dir=Path(tempfile.mkdtemp()), on_tool=lambda n, a, r: calls.append((n, a, r)))
    session = scenario.id
    per_turn, replies = [], []
    for text in scenario.turns:
        before = len(calls)
        reply = agent.respond(session, text)
        replies.append(reply)
        per_turn.append((reply, calls[before:]))
    return Result(replies=replies, calls=calls), per_turn, getattr(agent.llm, "model", "unknown")


def transcript(scenario: Scenario, per_turn, model: str) -> str:
    lines = [
        f"# {scenario.title}",
        "",
        f"Scenario `{scenario.id}`. {scenario.why}",
        f"Model: `{model}`. Store date used for deadlines: {STORE_TODAY}.",
        "",
    ]
    for text, (reply, tool_calls) in zip(scenario.turns, per_turn):
        lines += [f"**Customer:** {text}", ""]
        for name, args, result in tool_calls:
            lines.append(f"> tool `{name}` {json.dumps(args, ensure_ascii=False)}")
            lines.append(f">   result: {json.dumps(result, ensure_ascii=False)[:400]}")
        if tool_calls:
            lines.append("")
        lines += [f"**Maestro:** {reply}", ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--only", help="run scenarios whose id contains this text")
    parser.add_argument("--examples", action="store_true", help="write the delivered conversations to examples/")
    args = parser.parse_args()

    scenarios = [s for s in SCENARIOS if not args.only or args.only in s.id]
    report = ["# Evaluation results", "", f"Store date: {STORE_TODAY}. Generated by `eval/run.py`.", ""]
    failures = 0
    for scenario in scenarios:
        number = SCENARIOS.index(scenario) + 1  # stable file numbers even with --only
        started = time.time()
        result, per_turn, model = run_scenario(scenario)
        errors = [r["erro"] for n, _, r in result.calls if n == "llm_error"]
        failed = [name for name, check in scenario.checks if not check(result)]
        # A model error is never a pass: "does not say X" checks would hold for an apology.
        status = "ERROR" if errors else ("PASS" if not failed else "FAIL")
        failures += status != "PASS"
        detail = f"  {errors[0][:120]}" if errors else (f"  failed: {failed}" if failed else "")
        print(f"{status} {scenario.id} ({time.time() - started:.0f}s, {model}){detail}", flush=True)
        report += [f"## {status} {scenario.id}", f"{scenario.title}. {scenario.why}", f"Model: `{model}`.", ""]
        if errors:
            report += ["The model call failed, so nothing was checked. Re-run this scenario.", ""]
        else:
            report += [f"- [{'x' if name not in failed else ' '}] {name}" for name, _ in scenario.checks] + [""]
        if args.examples and scenario.example and status == "PASS":
            out = ROOT / "examples" / f"{number:02d}-{scenario.id}.md"
            out.parent.mkdir(exist_ok=True)
            out.write_text(transcript(scenario, per_turn, model), encoding="utf-8")
    summary = f"{len(scenarios) - failures}/{len(scenarios)} scenarios passed."
    print(summary)
    if not args.only:  # a partial run must not overwrite the full report
        report.insert(3, summary + "\n")
        (ROOT / "eval" / "results.md").write_text("\n".join(report), encoding="utf-8")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
